// セクションの日本語ラベル。
//
// メニュー（コマンド窓）専用のラベル。
//
// 見出し（EXPERIENCE 等）と Rail は英語のまま。あれはコンテンツの
// ラベルと現在地インジケータで、見出しと対応している必要がある。
// メニューだけが「どこへ行くか選ぶ」コマンドなので日本語で書く。
// ゲームのメニューに英語は並ばない。
//
// 漢字の名詞（経歴・取材・登壇）にすると資料の目次になる。ひらがなに
// 開いて「〜たこと」で語形を揃えた。桁を揃えるより効く。
// 連絡先だけ「はなしかける」— 町の人に話しかけるあれと同じ動作なので。
//
// 照合と移動には英語名（DOM の h2 テキスト）を使い、表示だけ差し替える。
export const SECTION_JA: Record<string, string> = {
  Experience: 'これまで',
  Interviews: 'きかれたこと',
  Speaking: 'はなしたこと',
  Writings: 'かいたもの',
  Services: 'できること',
  Contact: 'はなしかける',
};

export const labelOf = (name: string) => SECTION_JA[name] ?? name;
